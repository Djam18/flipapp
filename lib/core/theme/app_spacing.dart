/// Standardized spatial spacing system based on a strict 8-point grid.
abstract class AppSpacing {
  static const double xxs = 4.0;
  static const double xs = 8.0;
  static const double sm = 12.0;
  static const double md = 16.0; // Standard mobile screen horizontal padding
  static const double lg = 24.0; // Section separation
  static const double xl = 32.0;
  static const double xxl = 48.0; // Cockpit spacious margins

  // Border Radii
  static const double radiusSmall = 8.0;
  static const double radiusMedium = 16.0;
  static const double radiusLarge = 28.0;
  static const double radiusFull = 999.0;
}
